package com.paysphere.user;

import com.paysphere.BaseIntegrationTest;
import com.paysphere.user.entity.User;
import com.paysphere.user.entity.UserStatus;
import com.paysphere.user.repository.UserRepository;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.transaction.annotation.Transactional;

import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Integration Test: UserRepository
 *
 * Tests that the V1 Flyway migration produced the correct schema
 * and that Spring Data JPA operations work against real PostgreSQL.
 *
 * @Transactional on each test method means:
 * - The test runs inside a database transaction
 * - After the test finishes, the transaction is ROLLED BACK
 * - No test data leaks into subsequent tests
 * - Each test starts with a clean state
 *
 * This is the cleanest way to isolate test data without
 * resetting the entire database between every test.
 */
@DisplayName("UserRepository Integration Tests — Milestone 1 AT-3")
class UserRepositoryIntegrationTest extends BaseIntegrationTest {

    @Autowired
    private UserRepository userRepository;

    @Test
    @Transactional
    @DisplayName("AT-3: Can save and retrieve a user — confirms V1 migration created users table")
    void saveAndFindUser_confirmsMigrationApplied() {
        // Given: a new user
        User user = User.builder()
                .email("test.user@paysphere.local")
                .passwordHash("$2a$12$hashed_password_placeholder")  // BCrypt hash format
                .fullName("Test User")
                .status(UserStatus.ACTIVE)
                .build();

        // When: we save it
        User saved = userRepository.save(user);

        // Then: it has an auto-generated UUID
        assertThat(saved.getId())
                .as("UUID should be auto-generated by PostgreSQL")
                .isNotNull();

        // And: we can find it back by ID
        Optional<User> found = userRepository.findById(saved.getId());
        assertThat(found).isPresent();
        assertThat(found.get().getEmail()).isEqualTo("test.user@paysphere.local");
        assertThat(found.get().getFullName()).isEqualTo("Test User");
        assertThat(found.get().getStatus()).isEqualTo(UserStatus.ACTIVE);

        // And: timestamps were set automatically
        assertThat(found.get().getCreatedAt()).isNotNull();
        assertThat(found.get().getUpdatedAt()).isNotNull();
    }

    @Test
    @Transactional
    @DisplayName("findByEmail returns user when email exists")
    void findByEmail_returnsUser_whenEmailExists() {
        // Given
        User user = userRepository.save(User.builder()
                .email("find.me@paysphere.local")
                .passwordHash("$2a$12$hash")
                .fullName("Find Me")
                .build());

        // When
        Optional<User> found = userRepository.findByEmail("find.me@paysphere.local");

        // Then
        assertThat(found).isPresent();
        assertThat(found.get().getId()).isEqualTo(user.getId());
    }

    @Test
    @Transactional
    @DisplayName("findByEmail returns empty when email does not exist")
    void findByEmail_returnsEmpty_whenEmailNotFound() {
        Optional<User> found = userRepository.findByEmail("nonexistent@paysphere.local");
        assertThat(found).isEmpty();
    }

    @Test
    @Transactional
    @DisplayName("existsByEmail returns true when email is taken")
    void existsByEmail_returnsTrue_whenEmailRegistered() {
        userRepository.save(User.builder()
                .email("taken@paysphere.local")
                .passwordHash("$2a$12$hash")
                .fullName("Taken Email")
                .build());

        assertThat(userRepository.existsByEmail("taken@paysphere.local")).isTrue();
        assertThat(userRepository.existsByEmail("free@paysphere.local")).isFalse();
    }

    @Test
    @Transactional
    @DisplayName("Unique email constraint prevents duplicate accounts")
    void uniqueEmailConstraint_preventsInsertOfDuplicateEmail() {
        // Given: a user with email already saved
        userRepository.saveAndFlush(User.builder()
                .email("duplicate@paysphere.local")
                .passwordHash("$2a$12$hash")
                .fullName("First User")
                .build());

        // When: we try to save another user with the same email
        User duplicate = User.builder()
                .email("duplicate@paysphere.local")
                .passwordHash("$2a$12$hash")
                .fullName("Second User")
                .build();

        // Then: a DataIntegrityViolationException is thrown
        // (Spring translates the PostgreSQL unique constraint violation)
        assertThatThrownBy(() -> userRepository.saveAndFlush(duplicate))
                .as("Duplicate email should throw a constraint violation")
                .isInstanceOf(org.springframework.dao.DataIntegrityViolationException.class);
    }
}
